import { feature } from '@mantle/config';
/**
 * Constants shared between middleware (Edge runtime) and lib/auth.ts
 * (Node runtime). Both files validate the session cookie but can't share
 * full code — middleware uses Web Crypto, lib/auth uses node:crypto.
 * Pull anything that's just data (cookie name, public paths) in here.
 */

export const SESSION_COOKIE_NAME = 'mantle_session';

/**
 * The render cookie (kind 'r', lib/auth/tokens.ts): what the browser sidecar
 * carries on the print origin when it renders an export. Its own name, so it
 * can never be read as the session cookie.
 */
export const RENDER_COOKIE_NAME = 'mantle_render';

/** The byte routes a render surface loads: page images and scene images
 *  (/api/files/files/:id) and embedded drawings (/api/draws/:id/svg). Nothing
 *  else: not the admin private-space bytes, not any JSON API. The render
 *  pages themselves are ROUTE_POLICY rows of class 'render'
 *  (lib/auth/route-policy.ts); a row's `renderCookie` is what the gate reads. */
const RENDER_ASSET_RE = /^\/api\/(?:files\/files\/[^/]+|draws\/[^/]+\/svg)$/;

export function isRenderAssetPath(path: string): boolean {
  return RENDER_ASSET_RE.test(path);
}

/** Byte-serving asset routes whose <img>/<iframe>/download srcs can't carry a
 *  bearer header, so they may authenticate via a `?at=` asset token. Scoped
 *  narrowly: the asset token is accepted for NOTHING else. `/api/export/`
 *  is the download-anchor export surface: generated bytes rather than stored
 *  ones, but the same can't-carry-a-bearer link shape. The gate admits the
 *  token here (GET only), and ROUTE_POLICY lets the asset caller kinds be
 *  read only on a GET or HEAD row of these paths (route-policy.ts
 *  callerServes, A4 hand batch B fix round 1). */
export function isAssetPath(path: string): boolean {
  return (
    path.startsWith('/api/files/files/') ||
    path.startsWith('/api/attachments/') ||
    path.startsWith('/api/export/') ||
    // The user's profile photo: a private <img> src (the rail), same
    // can't-carry-a-bearer shape. GET-only byte serving, owner-scoped.
    path === '/api/profile/photo' ||
    // Drawing SVGs: the route has ALWAYS called getOwnerForAsset and its
    // header promises `?at=` auth for detached clients, but this list never
    // admitted the path, so the gate 401'd the token before the route ran
    // (worked same-origin via cookie, broken only detached). Registering an
    // asset route means BOTH ends: getOwnerForAsset in the route AND here.
    /^\/api\/draws\/[^/]+\/svg$/.test(path) ||
    // Member Library bytes (member logins): file bytes and drawing SVGs a
    // member may read. The routes call getMemberForAsset and read at the team
    // level, so the token opens only what the member's level can see.
    path.startsWith('/api/member/files/') ||
    /^\/api\/member\/draws\/[^/]+\/svg$/.test(path) ||
    // A member's own private file (member logins Phase 2). The member shell
    // mints the token for exactly these <img>/download srcs. The route calls
    // getMemberForAsset: the read runs in the space of the member the token's
    // `act` names, so the token opens only that member's items; another
    // member's file is a 404.
    /^\/api\/member\/space\/[^/]+\/bytes$/.test(path) ||
    // An admin's own private file (member logins Phase 7). The route calls
    // getOwnerForAsset and reads the space of the login the token's `act`
    // names, so the token opens only that admin's own items.
    /^\/api\/admin\/space\/[^/]+\/bytes$/.test(path)
    // The client byte routes (/api/client/files, draws, space bytes) were
    // removed in workspaces W5c: no token opens them; they answer 410 to a
    // client session.
  );
}

// `/s` is the public read-only share surface (token-gated, no session). The
// /s pages + /s/[token]/a/[fileId] asset route authorize by share token, not by
// the owner cookie — see docs/sharing.md.
// `/api/federation` is the inbound federation surface for peer Mantles. It
// authorizes by a per-peer bearer token (verifyInboundToken), not the owner
// cookie — so it must bypass the session gate. See docs/federation.md.
// `/api/version` exposes only the build identity (version/SHA/build time) — no
// sensitive data — so it stays open for uptime/ops probes. See docs/versioning.md.
// `/app-runtime` is the shared mini-app runtime (React + UI kit + host bridge) —
// open-source library code with no secrets or user data. Sandboxed app iframes
// load it with an OPAQUE origin (no session cookie), so it must bypass the gate.
export const PUBLIC_PATHS = [
  '/login',
  '/api/auth',
  // The QR sign-in URL's landing page for a browser that scanned it (the
  // phone app parses the URL itself and never opens it).
  '/pair',
  '/s',
  '/api/federation',
  '/api/version',
  // System-wide branding (colour theme + display fonts). Public because the
  // zero-secret client app must stamp it before first paint from a different
  // origin, and it's the same branding every /s share already renders openly.
  '/api/appearance',
  '/app-runtime',
  // The remote MCP endpoint self-authenticates with an OAuth bearer, so it must
  // bypass the session-cookie gate. See server/web/app/api/mcp/route.ts.
  '/api/mcp',
  // OAuth 2.1 authorization server for the MCP connector. register + token
  // self-authenticate; authorize is the exception — it USES the session but must
  // still bypass the middleware (it's a browser navigation that does its OWN
  // login redirect, where the gate would otherwise return 401 JSON). The
  // discovery docs are public metadata. See server/web/lib/mcp-oauth.ts.
  '/api/oauth',
  '/.well-known/oauth-authorization-server',
  '/.well-known/oauth-protected-resource',
  // /team, /hub and /api/team/* (the team-code portal) were retired in member
  // logins Phase 6: their old page URLs redirect to /login BEFORE this gate
  // (server/pages/stubs.ts mountRetiredTeamPages) and the API paths are gone.
];

/**
 * Whether `path` is under PUBLIC_PATHS: the one function that reads the
 * list. ROUTE_POLICY builds each row's `public` with it; the gate asks it
 * only for a request no row answers (arch A4 step 2).
 */
export function isPublicPath(path: string): boolean {
  return PUBLIC_PATHS.some((p) => path === p || path.startsWith(`${p}/`));
}

/**
 * Paths whose routes emit their own richer audit events (`user.*`) — the
 * choke point skips its generic `api.write` row for these to avoid doubles.
 */
export const AUDIT_SELF_LOGGED_PATHS = [
  '/api/users',
  '/api/team-admin/clients',
  '/api/services',
  // Inbound API keys write key.created / key.revoked.
  '/api/access-keys',
];

/** "External access" on a tool: setToolExternalAccess writes its own
 *  `tool.external_access.on` / `.off` row with the actor and the tool. */
const TOOL_EXTERNAL_ACCESS_PATH = /^\/api\/tools\/[^/]+\/external-access\/?$/;

export function isAuditSelfLogged(path: string): boolean {
  return (
    AUDIT_SELF_LOGGED_PATHS.some((p) => path === p || path.startsWith(p + '/')) ||
    TOOL_EXTERNAL_ACCESS_PATH.test(path)
  );
}

/**
 * Request-context headers injected by the middleware (overwritten there via
 * Headers.set, so a client-supplied value can't survive on any path middleware
 * runs on). They let the Node-side auth gate learn the method/path for audit
 * attribution without threading `Request` through the 280+ `getOwnerOr401()`
 * call sites. They drive audit labelling only — not an access decision — so a
 * spoof on a matcher-excluded path can at worst mislabel a row, not grant access.
 */
export const MANTLE_PATH_HEADER = 'x-mantle-path';
export const MANTLE_METHOD_HEADER = 'x-mantle-method';

/**
 * Whether cookies set on this response should carry the `Secure` attribute.
 * Decided from the request's actual scheme — NOT from NODE_ENV: production
 * builds also serve plain-HTTP installs (MANTLE_SITE_ADDRESS=:80 on a bare
 * IP, the documented no-domain mode), where browsers silently discard Secure
 * cookies — login "succeeds" but the session never sticks and the user loops
 * back to /login forever. Caddy sets X-Forwarded-Proto on every proxied
 * request; the URL scheme covers direct (proxy-less) access.
 */
export function secureCookies(req: Request): boolean {
  const fwd = req.headers.get('x-forwarded-proto');
  if (fwd) return fwd.split(',')[0]?.trim().toLowerCase() === 'https';
  return new URL(req.url).protocol === 'https:';
}

/**
 * Origin the user's browser actually reached the app on, derived from proxy
 * headers. NEVER build a user-facing absolute URL from `req.url` in a route
 * handler: Next's standalone server constructs it from the container's bind
 * address, so `new URL('/path', req.url)` redirects the browser to a dead
 * https://0.0.0.0:3000. First value wins on comma-joined multi-proxy headers.
 */
export function requestOrigin(req: Request): string {
  const first = (v: string | null) => v?.split(',')[0]?.trim() || undefined;
  const host =
    first(req.headers.get('x-forwarded-host')) ??
    first(req.headers.get('host')) ??
    'localhost:3000';
  const proto =
    first(req.headers.get('x-forwarded-proto'))?.toLowerCase() ??
    (host.startsWith('localhost') ? 'http' : 'https');
  return `${proto}://${host}`;
}

/**
 * DB-less "detached" dev: a local frontend pointed at a remote API
 * (`NEXT_PUBLIC_MANTLE_API_BASE`) with no local Postgres. The dev auth shim in
 * `lib/auth` (`detachedDevUser`) and the page-nav bypass in `middleware.ts` both
 * gate on this.
 *
 * Master switch is a SERVER-ONLY env var (deliberately NOT `NEXT_PUBLIC_`, so it
 * can never be flipped on from a shipped client bundle) AND it is hard-disabled
 * in production — so the bypass can NEVER activate in a prod build, regardless of
 * how the public API vars are set. Env-only (no node:crypto), so it is safe to
 * call from the Edge middleware. See docs/db-less-dev.md.
 */
export function isDetachedDev(): boolean {
  return feature('detachedDev');
}
