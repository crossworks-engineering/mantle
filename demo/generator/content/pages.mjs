// PAGES: six, written to show what a page can hold. Images from Files
// (`media:gen:`), page link cards (`page:gen:`), mentions of other items
// (`mention:node:gen:`), callouts, columns, tables, to-do lists, a foldable
// heading and one formula in math. The seeder swaps every `gen:<id>` for the
// real id once that item exists, so a page may only point at items created
// before it (the test checks the order).
//
// Levels: two team pages, the procedure revision family for the client
// (rev A superseded by rev B), one private page and one public page.
// Images always come from the same tier's Files folder; mentions may point
// at anything the page's readers can also read (a team page may mention a
// client item; a client page mentions client items only).

