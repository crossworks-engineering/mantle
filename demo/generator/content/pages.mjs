    '3. Wire the new RTU in parallel. The old RTU keeps reporting until H3.',
    '4. Sign **H1**, then isolate the old RTU outputs only. Its inputs stay live.',
    '5. Loop check in the rev B order: LT-101, FT-201, PT-301, then the XV-401 fail-safe test.',
    '6. Sign **H2** once the level loop reads the same at the sensor and on the control room screen.',
    '7. Pull the radio link for sixty seconds and confirm XV-401 holds position.',
    '8. Sign **H3**. The control room takes the station on the new RTU.',
